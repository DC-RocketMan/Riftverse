package dev.riftverse.story;

/** Plot-Twist, der in der letzten Kampfphase enthüllt wird. */
public enum Twist {
    NONE,
    /** Der Boss ist eine Version des Spielers aus einer anderen Zeitlinie. */
    ALTERNATE_SELF,
    /** Der Boss wird von einer höheren Macht gesteuert. */
    PUPPET,
    /** Der Boss beschwört Klone von sich selbst. */
    CLONE,
    /** Der Boss wollte das Universum vor den Rifts des Spielers schützen. */
    VICTIM,
    /** Der Boss verändert die Gravitation in der Arena. */
    PHYSICS
}
